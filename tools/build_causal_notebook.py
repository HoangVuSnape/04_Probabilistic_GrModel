        "# Section 10.1: Neural NOTEARS with Domain Mask & Cycle Repair",
        "# ==============================================================================",
        "def build_domain_mask(cfg: Config) -> np.ndarray:",
        "    \"\"\"",
        "    Xây dựng Ma trận mặt nạ cấm cạnh miền M (Slide 63).",
        "    M[i, j] = 0 nếu cấm cạnh i -> j, ngược lại M[i, j] = 1.",
        "    Thứ tự biến: [Z1, Z2, Z3, Z4, Z5, T, Y] (nodes 0..6).",
        "    \"\"\"",
        "    d = len(cfg.all_nodes)",
        "    M = np.ones((d, d), dtype=np.float32)",
        "    np.fill_diagonal(M, 0.0)  # Cấm tự nối",
        "    ",
        "    idx_map = {name: idx for idx, name in enumerate(cfg.all_nodes)}",
        "    t_idx = idx_map[cfg.treatment]",
        "    y_idx = idx_map[cfg.outcome]",
        "    z_indices = [idx_map[z] for z in cfg.confounders]",
        "    ",
        "    # 1. Cấm Outcome Y tác động ngược vào Treatment T hoặc Confounders Z",
        "    M[y_idx, t_idx] = 0.0",
        "    for z_i in z_indices:",
        "        M[y_idx, z_i] = 0.0",
        "        ",
        "    # 2. Cấm Treatment T tác động ngược vào Confounders Z thời điểm nhập học",
        "    for z_i in z_indices:",
        "        M[t_idx, z_i] = 0.0",
        "        ",
        "    return M",
        "",
        "class NOTEARSModel(nn.Module):",
        "    \"\"\"Mô hình tối ưu ma trận kề W liên tục có tích hợp ma trận mặt nạ M.\"\"\"",
        "    def __init__(self, d: int, mask: np.ndarray):",
        "        super().__init__()",
        "        self.d = d",
        "        self.register_buffer('mask', torch.tensor(mask, dtype=torch.float32))",
        "        self.W = nn.Parameter(torch.zeros(d, d, dtype=torch.float32))",
        "        nn.init.uniform_(self.W, -0.05, 0.05)",
        "        ",
        "    def get_w_eff(self) -> torch.Tensor:",
        "        return self.W * self.mask",
        "        ",
        "    def forward(self, X: torch.Tensor) -> torch.Tensor:",
        "        return torch.matmul(X, self.get_w_eff())",
        "",
        "def compute_h_acyclicity(W_eff: torch.Tensor) -> torch.Tensor:",
        "    \"\"\"Tính hàm phạt phi chu trình: h(W) = Tr(expm(W_eff ∘ W_eff)) - d.\"\"\"",
        "    d = W_eff.shape[0]",
        "    M = W_eff * W_eff",
        "    return torch.trace(torch.matrix_exp(M)) - d",
        "",
        "def train_h2_notears(",
        "    train_df: pd.DataFrame,",
        "    cfg: Config,",
        "    seed: int",
