        "    X_mean = X.mean(dim=0, keepdim=True)",
        "    X_std = X.std(dim=0, keepdim=True) + 1e-6",
        "    X_norm = (X - X_mean) / X_std",
        "    ",
        "    model = NOTEARSModel(d, mask)",
        "    optimizer = optim.Adam(model.parameters(), lr=cfg.h2_lr)",
        "    ",
        "    rho = 1.0",
        "    alpha = 0.0",
        "    h_val = float('inf')",
        "    ",
        "    # Vòng lặp tối ưu hóa kép (Dual Augmented Lagrangian)",
        "    for step in range(cfg.h2_epochs):",
        "        optimizer.zero_grad()",
        "        X_pred = model(X_norm)",
        "        w_eff = model.get_w_eff()",
        "        ",
